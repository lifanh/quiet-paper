#!/usr/bin/env node
/**
 * Generates the token layer from src/tokens/tokens.ts:
 *   - dist/tokens.css          plain :root custom properties, no Tailwind
 *   - dist/tokens.json         same tokens, machine-readable
 *   - styles/tokens.css        back-compat copy for `layer(theme)` consumers
 *   - styles/tailwind-theme.css  generated Tailwind v4 @theme bridge
 *
 * Run via `npm run build` (see package.json). Never hand-edit the outputs.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { tokenGroups } from "../src/tokens/tokens.ts";

const root = dirname(fileURLToPath(import.meta.url)) + "/..";
const distDir = resolve(root, "dist");
const stylesDir = resolve(root, "styles");

function buildTokensCss() {
	const lines = [
		"/**",
		" * @lifanh/quiet-paper — canonical design tokens",
		" * GENERATED by scripts/build-tokens.mjs from src/tokens/tokens.ts — do not edit.",
		" * Plain CSS, no Tailwind: drop this file into any page and every",
		" * --name below resolves via getComputedStyle.",
		" */",
		":root {",
	];
	for (const { comment, tokens } of tokenGroups) {
		lines.push(`    /* ${comment} */`);
		for (const { name, value } of tokens) {
			lines.push(`    --${name}: ${value};`);
		}
		lines.push("");
	}
	while (lines[lines.length - 1] === "") lines.pop();
	lines.push("}", "");
	return lines.join("\n");
}

function buildTokensJson() {
	const out = {};
	for (const { tokens } of tokenGroups) {
		for (const { name, value } of tokens) {
			out[`--${name}`] = value;
		}
	}
	return JSON.stringify(out, null, 2) + "\n";
}

function buildTailwindThemeCss() {
	const lines = [
		"/**",
		" * Tailwind v4 @theme bridge — GENERATED by scripts/build-tokens.mjs",
		" * from src/tokens/tokens.ts — do not edit.",
		" * Import after tokens.css in app global.css:",
		' * @import "@lifanh/quiet-paper/styles/tokens.css" layer(theme);',
		' * @import "@lifanh/quiet-paper/styles/tailwind-theme.css";',
		" */",
		"@theme {",
	];
	let firstGroup = true;
	for (const { comment, tokens } of tokenGroups) {
		const bridged = tokens.filter((t) => t.tw);
		if (bridged.length === 0) continue;
		if (!firstGroup) lines.push("");
		firstGroup = false;
		for (const { name, tw } of bridged) {
			lines.push(`    --${tw}: var(--${name});`);
		}
	}
	lines.push("}", "");
	return lines.join("\n");
}

function assertNoTailwindInternals(css) {
	if (/--tw-/.test(css)) {
		throw new Error(
			"build-tokens: generated tokens.css contains a --tw- custom property; " +
				"Tailwind internals must never appear in the standalone token layer.",
		);
	}
	if (/@theme|@layer/.test(css)) {
		throw new Error(
			"build-tokens: generated tokens.css contains @theme or @layer; " +
				"it must be plain CSS with no Tailwind involvement.",
		);
	}
}

const tokensCss = buildTokensCss();
const tokensJson = buildTokensJson();
const tailwindThemeCss = buildTailwindThemeCss();

assertNoTailwindInternals(tokensCss);

await mkdir(distDir, { recursive: true });
await writeFile(resolve(distDir, "tokens.css"), tokensCss);
await writeFile(resolve(distDir, "tokens.json"), tokensJson);
await writeFile(resolve(stylesDir, "tokens.css"), tokensCss);
await writeFile(resolve(stylesDir, "tailwind-theme.css"), tailwindThemeCss);

console.log("build-tokens: wrote dist/tokens.{css,json}, styles/tokens.css, styles/tailwind-theme.css");
